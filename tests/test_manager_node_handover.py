"""`node install` hands an older deployment's launchd agents over itself.

Before the node manager runs a folder's services, the launchd agents an older
deployment's host-agents compilation left for them are taken down and out of
~/Library/LaunchAgents, so none runs twice. The manager is loaded as a module
and launchd is stood in for.
"""

from __future__ import annotations

import importlib.machinery
import importlib.util
import json
import plistlib
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
MANAGER = REPO / "bin" / "capabilities"
COMPILED = ('<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by deployment sync '
            '(capabilities.deployment.generated.v1); do not edit this file directly. -->\n'
            '<plist version="1.0"><dict/></plist>\n')


def _manager_module():
    loader = importlib.machinery.SourceFileLoader(
        "capabilities_manager_node_handover", str(MANAGER))
    spec = importlib.util.spec_from_loader(loader.name, loader)
    module = importlib.util.module_from_spec(spec)
    loader.exec_module(module)
    return module


M = _manager_module()


@pytest.fixture
def mac(tmp_path, monkeypatch):
    """A host-agents project, an installed capability that bundles a service,
    and a launchd that answers from a set of loaded labels."""
    root = tmp_path / "project"
    (root / "deployment").mkdir(parents=True)
    (root / "deployment" / "runtime.json").write_text(json.dumps({"profile": "host-agents"}))
    registry = tmp_path / "registry"
    (registry / "telegram").mkdir(parents=True)
    (registry / "telegram" / "manifest.json").write_text(json.dumps(
        {"name": "telegram", "service": {"name": "telegram"}}))
    monkeypatch.setattr(M, "CAP_HOME", registry)
    monkeypatch.setenv("HOME", str(tmp_path / "home"))
    library = tmp_path / "home" / "Library" / "LaunchAgents"
    library.mkdir(parents=True)
    loaded: set[str] = set()
    calls: list[tuple] = []

    def launchctl(*argv, timeout=60):
        calls.append(argv)
        label = argv[1].rsplit("/", 1)[-1]
        if argv[0] == "print":
            return (0, "") if label in loaded else (113, "not found")
        if argv[0] == "bootout":
            loaded.discard(label)
        return 0, ""

    monkeypatch.setattr(M, "_launchctl", launchctl)
    return {"root": root, "library": library, "loaded": loaded, "calls": calls,
            "agents": root / "deployment" / "launchd", "tmp": tmp_path}


def test_handover_takes_down_the_service_agents_and_the_watchdog_only(mac) -> None:
    agents, library, loaded, calls = mac["agents"], mac["library"], mac["loaded"], mac["calls"]
    agents.mkdir(parents=True)
    for label in ("project.telegram", "project.watchdog", "project.node-sync-production"):
        (agents / f"{label}.plist").write_text(COMPILED)
    (agents / "project.mine.plist").write_text(COMPILED.replace("Generated by", "Written by"))
    (library / "project.telegram.plist").symlink_to(agents / "project.telegram.plist")
    (library / "project.watchdog.plist").write_text("copied in by hand\n")
    (library / "project.node-sync-production.plist").symlink_to(
        agents / "project.node-sync-production.plist")
    loaded |= {"project.telegram", "project.watchdog", "project.node-sync-production"}

    preview = M._project_handover(mac["root"], True)
    assert [(a["label"], a["kind"], a["action"]) for a in preview] == [
        ("project.telegram", "service", "would_hand_over"),
        ("project.watchdog", "watchdog", "would_hand_over")]
    assert all(argv[0] == "print" for argv in calls) and len(loaded) == 3

    done = M._project_handover(mac["root"], False)
    assert [a["action"] for a in done] == ["handed_over"] * 2
    assert M._handover_failed(done) is None
    assert [argv[1].rsplit("/", 1)[-1] for argv in calls if argv[0] == "bootout"] == [
        "project.telegram", "project.watchdog"]
    assert loaded == {"project.node-sync-production"}
    assert not (library / "project.telegram.plist").exists()
    assert (library / "project.node-sync-production.plist").is_symlink()
    kept = agents / "project.watchdog.plist.handed-over"
    assert done[1]["kept_at"] == str(kept) and kept.read_text() == "copied in by hand\n"
    # The compiled files stay; a second run finds nothing to hand over.
    assert (agents / "project.telegram.plist").is_file()
    again = M._project_handover(mac["root"], False)
    assert [a["action"] for a in again] == ["absent", "absent"]


def test_handover_finds_every_loaded_agent_of_the_folder_whatever_compiled_it(mac) -> None:
    """An older compilation's agents under another label, loaded from a file
    put in ~/Library/LaunchAgents, are this folder's too."""
    root, library, loaded = mac["root"], mac["library"], mac["loaded"]
    launchers = mac["agents"]

    def agent(label, program, **extra):
        (library / f"{label}.plist").write_bytes(plistlib.dumps(
            {"Label": label, "ProgramArguments": [str(program)], **extra}))

    agent("legacy.telegram", launchers / "legacy-telegram")
    agent("legacy.watchdog", launchers / "legacy-watchdog")
    agent("legacy.backup", root / "scripts" / "backup")
    agent("elsewhere.telegram", mac["tmp"] / "elsewhere" / "telegram")
    agent("capabilities.node", "/usr/local/bin/capabilities", WorkingDirectory=str(root))
    loaded |= {"legacy.telegram", "legacy.watchdog", "legacy.backup", "elsewhere.telegram",
               "capabilities.node"}

    preview = M._project_handover(root, True)
    assert [(a["label"], a["kind"], a.get("service"), a["action"]) for a in preview] == [
        ("legacy.backup", "other", None, "kept"),
        ("legacy.telegram", "service", "telegram", "would_hand_over"),
        ("legacy.watchdog", "watchdog", None, "would_hand_over")]
    done = M._project_handover(root, False)
    assert [a["action"] for a in done] == ["kept", "handed_over", "handed_over"]
    # What runs nothing the node manager takes over keeps running, and so
    # does what is not this folder's.
    assert loaded == {"legacy.backup", "elsewhere.telegram", "capabilities.node"}
    assert not (library / "legacy.telegram.plist").exists()
    assert (launchers / "legacy.telegram.plist.handed-over").is_file()
